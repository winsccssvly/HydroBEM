"""Writes python/hydrobem/_result_views.py, and the tree and the table of the result views in
docs/reference/results.md, from the result tree of the engine (``_core.result_views``,
``_core.result_groups``): per group of the tree a view class with a property per view (the
engine's selection of an owner's part, ``Results._select``) and per child group, the view of a
body (``BodyResults``) and ``Results`` itself (its views, its groups and the list of the bodies).
Every public class of the results is defined there; what a class has beyond the tree is written by
hand in python/hydrobem/_result_extras.py, a base the generated class names (``EXTRAS``).

    python scripts/gen_result_views.py            # writes the files
    python scripts/gen_result_views.py --check    # exit 1 when a file is not up to date

The extension module must be built (the tree is read through hydrobem._core).
"""

from __future__ import annotations

import argparse
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "python" / "hydrobem" / "_result_views.py"
DOC = ROOT / "docs" / "reference" / "results.md"
BEGIN = "<!-- result views: generated by scripts/gen_result_views.py, do not edit -->"
END = "<!-- end of the result views -->"
TREE_BEGIN = "<!-- result tree: generated by scripts/gen_result_views.py, do not edit -->"
TREE_END = "<!-- end of the result tree -->"
sys.path.insert(0, str(ROOT / "python"))

# the class of a group whose name is not its path in CamelCase
NAMES = {"body_points": "BodyPointResults", "field_points": "FieldPointResults", "lids": "LidResults",
         "pressure_surfaces": "PressureSurfaceResults", "tanks": "TankResults"}  # fmt: skip
# the hand-written base of a generated class (python/hydrobem/_result_extras.py): of the results
# (""), of the view of a body ("body") and of a group
EXTRAS = {"": "_ResultsExtras", "body": "_BodyExtras"}
# the owner lists: the text of their KeyError and how the owners are named, and the index of an
# owner in the tree
OWNER_LISTS = {"lids": "lid", "pressure_surfaces": "pressure surface", "tanks": "tank"}
OWNER_INDEX = {"lids": "l", "pressure_surfaces": "s", "tanks": "t"}
# the symbols of the axes (reference/results)
AXES = {"frequency": "F", "heading": "H", "coordinate": "D", "radiation_column": "K", "field_point": "J",
        "drift_heading_pair": "P", "qtf_heading_pair": "P", "lid_point": "L", "pressure_point": "Q",
        "tank_point": "M", "body_point": "N", "angle": "A", "body": "B", "3*body": "3 B"}  # fmt: skip
# an owner's part of an axis by the rule
PART = {"coordinates": {"D": "D_b", "K": "K_b"}, "body_points": {"N": "N_b"}, "lid": {"L": "L_l"},
        "pressure_surface": {"Q": "Q_s"}, "tank": {"M": "M_t"}}  # fmt: skip
OF_BODY = ("shared", "columns", "coordinates", "body_points", "pressure_surface", "tank")
# the rules of the owners of a list of each body (no view of the results)
BODY_LISTS = ("pressure_surface", "tank")
BODY_DOC = ("The results of one body (``results.bodies[name]``): views of the global arrays, read-only, None when "
            "not computed. D_b its coordinates, K_b its radiation columns, N_b its body points; the coupled "
            "coefficients between bodies stay on the results; its pressure surfaces and tanks are lists of it. Its "
            "``index``, ``name``, ``coordinates`` and ``hydrostatics`` are those of its base ``_BodyExtras``.")
RESULTS_DOC = ("The results of a solve, of a results file, or given as arrays (``Results.of``): the views of the "
               "result tree (reference/results §1), dimensional (SI, unit wave amplitude), read-only, None when "
               "not computed. The axes and the quantities read by body are its properties of their names "
               "(``omegas``, ``headings``, ``added_mass``, ``motion``, ...), the others are in its groups "
               "(``excitation``, ``body_points``, ``field_points``, ``kochin``, ``drift``, ``qtf``, ``hydrostatics``) "
               "and in its owners (``lids[name]``, ``bodies[name]``); a quantity by its name: ``quantity(name)`` "
               "(the list is "
               "``hb.quantities()``). The first-order quantities are in body axes about each body's rotation "
               "centre R; the mean drift moments as theory §1.1. Axes: F the ordinary frequencies (``omegas``), "
               "H the headings (``headings``), D the coordinates (``coordinates``), K the radiation columns "
               "(``radiation_mode_ids``). Its loading, meta data, coordinates, ``coefficient``, ``coordinate``, "
               "``normalized``, ``save`` and ``write_wamit`` are those of its base ``_ResultsExtras``.")


def _tree():
    from hydrobem import _core

    quantities = _core.quantities()
    views = _core.result_views()
    for v in views:
        v["info"] = quantities[v["code"]]
    return views, _core.result_groups()


def _parent(path: str) -> str:
    return path.rsplit(".", 1)[0] if "." in path else ""


def _leaf(path: str) -> str:
    return path.rsplit(".", 1)[-1]


def _class(group: str) -> str:
    return NAMES.get(group) or "".join(s.capitalize() for p in group.split(".") for s in p.split("_")) + "Results"


def _shapes(v: dict) -> tuple[str, str]:
    """The axes of the whole array and of an owner's part, e.g. "F, P, D" and "F, P, D_b"."""
    whole = [AXES.get(a, a) for a in v["info"]["dims"]]
    part = [PART.get(v["owner"], {}).get(a, a) for a in whole]
    if v["owner"] == "columns":
        part[-1] = str(v["width"])
    return ", ".join(whole), ", ".join(part)


def _under(views, group: str) -> list[dict]:
    """The views in the subtree of a group ("" the root)."""
    return [v for v in views if group == "" or v["path"].startswith(group + ".")]


def _contexts(views, group: str) -> tuple[bool, bool]:
    """Whether a group is a group of the results and whether of a body."""
    sub = _under(views, group)
    top = any(v["owner"] not in BODY_LISTS for v in sub)
    body = any(v["owner"] in OF_BODY for v in sub)
    return top, body


def _doc(text: str, indent: int) -> str:
    lines = []
    for para in text.split("\n\n"):
        lines += textwrap.wrap(para, 116 - indent) or [""]
        lines.append("")
    pad = " " * indent
    body = "\n".join((pad + x) if x else "" for x in lines[:-1]).lstrip()
    return f'{pad}"""{body}"""'


def _sentence(text: str) -> str:
    return text[0].upper() + text[1:] + ("" if text.endswith(".") else ".")


def _view_doc(v: dict, top: bool, body: bool) -> str:
    """The docstring of a view: its shape (of the results and of an owner), the description, element
    type and unit of its quantity."""
    whole, part = _shapes(v)
    o = v["owner"]
    if o in ("lid", "pressure_surface", "tank") or (o in ("coordinates", "body_points") and not top):
        shape = f"[{part}]"
    elif o == "global":
        shape = f"[{whole}]" + (" (None for a body)" if body else "")
    elif o == "shared" or not body:
        shape = f"[{whole}]"
    else:
        shape = f"[{whole}] (of a body [{part}])"
    info = v["info"]
    unit = f"; {info['unit']}" if info["unit"] not in ("", "1") else ""
    return (f"{shape} {info['description']}.\n\n``{info['name']}`` ({info['dtype']}{unit}), "
            f"rule {o}; None when not computed.")


def _members(views, groups, group: str, top: bool, body: bool, root: str = "") -> list[tuple[str, str]]:
    """The properties of the class of a group, (name, text) each: its views and its child groups, in
    the order of the quantity table. ``root`` "body" or "results" for the root of the tree: of a body
    its views (those read by body) and its groups, of the results every view of one segment (the
    quantities themselves) and its groups."""
    body_root, results_root = root == "body", root == "results"
    out, seen = [], set()
    for v in views:
        p = v["path"]
        if _parent(p) == group:
            if body_root and v["owner"] not in OF_BODY:
                continue
            out.append((_leaf(p), f'''
    @property
    def {_leaf(p)}(self) -> np.ndarray | None:
{_doc(_view_doc(v, top, body), 8)}
        return self._get("{p}")
'''))
            continue
        # the child group of this group on the path of the view
        rest = p[len(group) + 1:] if group else p
        child = (group + "." if group else "") + rest.split(".")[0]
        if child in seen or child not in groups:
            continue
        ctop, cbody = _contexts(views, child)
        if (body_root and not cbody) or (results_root and not ctop):
            continue
        seen.add(child)
        doc = _sentence(groups[child])
        res = "self" if results_root else "self._res"
        b = "None" if results_root else "self._body"
        if child in OWNER_LISTS:
            out.append((_leaf(child), f'''
    @property
    def {_leaf(child)}(self) -> _OwnerList:
{_doc(f"{doc} A list of ``{_class(child)}``, by name or position.", 8)}
        return {res}._owner_list("{child}", {b}, {_class(child)})
'''))
        else:
            out.append((_leaf(child), f'''
    @property
    def {_leaf(child)}(self) -> {_class(child)}:
{_doc(doc, 8)}
        return {_class(child)}({res}, {b})
'''))
    return out


def _class_text(name: str, base: str, doc: str, members: list[tuple[str, str]]) -> list[str]:
    """A generated class: its name, base, docstring and members. A member named as an attribute of
    its hand-written base is refused (the generated property would hide it)."""
    if base in EXTRAS.values():
        from hydrobem import _result_extras

        clash = [n for n, _ in members if hasattr(getattr(_result_extras, base), n)]
        assert not clash, f"{name}: the views {clash} would hide attributes of {base}"
    return [f"\n\nclass {name}({base}):\n{_doc(doc, 4)}\n\n    __slots__ = ()\n"] + [text for _, text in members]


def generate() -> str:
    if not OUT.exists():  # the package imports the classes: a first generation starts from none
        stub = ["BodyResults", "BodyPointResults", "ExcitationResults", "FieldPointResults", "LidResults",
                "PressureSurfaceResults", "Results", "TankResults"]
        OUT.write_bytes("".join(f"class {c}:\n    pass\n\n\n" for c in stub).encode())
    views, group_list = _tree()
    groups = {g["path"]: g["description"] for g in group_list}
    for g in EXTRAS:
        assert g in ("", "body") or g in groups, f"no group {g} to extend"
    for v in views:
        assert "." in v["path"] or v["path"] == v["info"]["name"], f"a view of one segment is its quantity: {v}"
        assert _parent(v["path"]) == "" or _parent(v["path"]) in groups, f"no group of {v['path']}"
    out = ['''"""The classes of the results by group and by owner (reference/results §1), generated by
scripts/gen_result_views.py from the result tree of the engine: do not edit. Each property is the
engine's selection of a quantity for the owner of the view (``Results._select``): the whole
array, a slice of it where the rows are contiguous, else a read-only copy of the rows; None when
not computed. What a class has beyond the tree is in its hand-written base (``_result_extras``)."""

# fmt: off
from __future__ import annotations

import numpy as np

from ._result_extras import _BodyExtras, _OwnerList, _OwnerView, _ResultsExtras, _View
''']
    # the groups, children after their parents (a class refers to its children at call time)
    for g in groups:
        top, body = _contexts(views, g)
        base = EXTRAS.get(g) or ("_OwnerView" if g in OWNER_LISTS else "_View")
        out += _class_text(_class(g), base, _sentence(groups[g]), _members(views, groups, g, top, body))
    # the view of a body: its views and groups
    out += _class_text("BodyResults", EXTRAS["body"], BODY_DOC, _members(views, groups, "", False, True, root="body"))
    # the results: the list of the bodies, its views and groups
    bodies = ("bodies", '''
    @property
    def bodies(self) -> _OwnerList:
        """The results of each body (``BodyResults``: views of the global arrays), by name or position:
        ``results.bodies["spar"].added_mass``."""
        return self._owner_list("bodies", None, BodyResults)
''')
    members = [bodies] + _members(views, groups, "", True, False, root="results")
    out += _class_text("Results", EXTRAS[""], RESULTS_DOC, members)
    names = sorted({_class(g) for g in groups} | {"BodyResults", "Results"})
    out.append("\n\n__all__ = [\n" + "".join(f'    "{n}",\n' for n in names) + "]\n")
    return "".join(out)


def _python(v: dict) -> tuple[str, str]:
    """The Python attribute of a view on the results and on an owner ("" for none)."""
    p, o = v["path"], v["owner"]
    if o == "lid":
        return "", f"lids[l].{_leaf(p)}"
    if o == "pressure_surface":
        return "", f"bodies[b].pressure_surfaces[s].{_leaf(p)}"
    if o == "tank":
        return "", f"bodies[b].tanks[t].{_leaf(p)}"
    body = f"bodies[b].{p}" if o in OF_BODY else ""
    return p, body


def doc_table() -> str:
    """The table of the result views of reference/results §1."""
    views, _ = _tree()
    rows = ["| View | Quantity | Rule | Results | An owner |", "|---|---|---|---|---|"]
    for v in views:
        whole, part = _shapes(v)
        top, owner = _python(v)
        o = v["owner"] + (f" ({v['width']})" if v["owner"] == "columns" else "")
        if v["owner"] == "global" and _parent(v["path"]) == "drift":
            owner = f"`bodies[b].{v['path']}`: None"
        elif owner:
            owner = f"`{owner}` [{whole if v['owner'] == 'shared' else part}]"
        results = f"`{top}` [{whole}]" if top else ""
        rows.append(f"| `{v['path']}` | `{v['info']['name']}` | {o} | {results} | {owner} |")
    return "\n".join(rows)


def _tree_lines(views, groups, group: str, root: str, pad: str) -> list[str]:
    """The lines of the subtree of a group ("" the root) of the results (``root`` "results") or of
    a body ("body"): its views (name, shape and quantity) and its child groups, in the order of the
    quantity table; on the results the list of the bodies where the first view of a body's own
    list would be."""
    items, seen = [], set()
    for v in views:
        p = v["path"]
        if group and not p.startswith(group + "."):
            continue
        rest = p[len(group) + 1:] if group else p
        head = rest.split(".")[0]
        child = (group + "." if group else "") + head
        if "." not in rest:
            if root == "body" and v["owner"] not in OF_BODY:
                continue
            whole, part = _shapes(v)
            own = (root == "body" and v["owner"] != "shared") or v["owner"] in BODY_LISTS + ("lid",)
            shape = part if own else whole
            items.append((f"{head} [{shape}]", v["info"]["name"], None))
            continue
        if child in seen:
            continue
        top, body = _contexts(views, child)
        if root == "results" and not top:
            if "bodies" not in seen:
                seen.add("bodies")
                items.append(("bodies[b]", "", ""))
            continue
        if root == "body" and not body:
            continue
        seen.add(child)
        name = f"{head}[{OWNER_INDEX[child]}]" if child in OWNER_LISTS else head
        items.append((name, "", child))
    lines = []
    for k, (name, quantity, sub) in enumerate(items):
        last = k == len(items) - 1
        text = pad + ("└─ " if last else "├─ ") + name
        if quantity:
            text = text.ljust(52) + " " + quantity
        lines.append(text.rstrip())
        deeper = pad + ("   " if last else "│  ")
        if sub == "":  # the bodies
            lines += _tree_lines(views, groups, "", "body", deeper)
        elif sub is not None:
            lines += _tree_lines(views, groups, sub, root, deeper)
    return lines


def doc_tree() -> str:
    """The result tree of reference/results §1: every view on the results and on a body, its shape
    (an owner's part on an owner) and its quantity."""
    views, group_list = _tree()
    groups = {g["path"]: g["description"] for g in group_list}
    return "\n".join(["```", "results", *_tree_lines(views, groups, "", "results", ""), "```"])


def doc_text() -> str:
    """results.md with the tree and the table of the result views between their markers."""
    text = DOC.read_text(encoding="utf-8")
    for begin, end, body in ((TREE_BEGIN, TREE_END, doc_tree()), (BEGIN, END, doc_table())):
        a, b = text.index(begin) + len(begin), text.index(end)
        text = text[:a] + "\n" + body + "\n" + text[b:]
    return text


def main() -> int:
    ap = argparse.ArgumentParser(description="Writes the result views from the engine's result tree.")
    ap.add_argument("--check", action="store_true", help="exit 1 when a file is not up to date; write nothing")
    check = ap.parse_args().check
    if check and not OUT.exists():  # a check changes nothing (generate would write the first stub)
        print(f"{OUT} does not exist: run scripts/gen_result_views.py")
        return 1
    files = [(OUT, generate()), (DOC, doc_text())]
    if check:
        # the bytes (LF line endings), not the text read with its line endings translated
        stale = [p for p, text in files if not p.exists() or p.read_bytes() != text.encode("utf-8")]
        for p in stale:
            print(f"{p} is not the output of scripts/gen_result_views.py for this result tree: run it")
        return 1 if stale else 0
    for p, text in files:
        p.write_bytes(text.encode("utf-8"))
        print(f"wrote {p}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
