"""Generates crates/hydrobem/src/tables/log_gauss_table.rs.

The generalized Gauss rule of N = 12 nodes on [0, 1] that integrates p^k and p^k log p exactly
for k = 0..N-1 (2N conditions on N nodes and N weights; Ma, Rokhlin & Wandzura 1996): the rule
of the radial variable of the Duffy integrals of a target on a surface in z = 0, whose
integrand is A(p) log p + B(p) with A, B smooth (theory §7.1). Solved by Newton's method in
40-digit arithmetic from Gauss-Legendre nodes mapped by p = t^2; the nodes are checked to lie in
(0, 1), the weights to be positive, and every moment to hold to 1e-30 before the table is
written (17 significant digits, the shortest that round trip).

Usage: python scripts/gen_log_gauss.py [--check]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import mpmath as mp
import numpy as np

N = 12
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "crates" / "hydrobem" / "src" / "tables" / "log_gauss_table.rs"


def moments(x, w):
    """The residuals of the 2N moment conditions."""
    out = []
    for k in range(N):
        out.append(mp.fsum(w[i] * x[i] ** k for i in range(N)) - mp.mpf(1) / (k + 1))
        out.append(mp.fsum(w[i] * x[i] ** k * mp.log(x[i]) for i in range(N)) + mp.mpf(1) / (k + 1) ** 2)
    return out


def rule():
    mp.mp.dps = 40
    g, gw = np.polynomial.legendre.leggauss(N)
    t = 0.5 * (g + 1)
    x0 = [mp.mpf(v) ** 2 for v in t]
    w0 = [mp.mpf(gw[i] * t[i]) for i in range(N)]  # 0.5 gw dp/dt with dp/dt = 2t
    z = mp.findroot(lambda *z: moments(z[:N], z[N:]), x0 + w0, tol=mp.mpf(10) ** -35, maxsteps=200)
    x, w = list(z[:N]), list(z[N:])
    if not all(0 < v < 1 for v in x) or not all(v > 0 for v in w):
        sys.exit("the rule has a node outside (0, 1) or a weight not positive")
    if max(abs(r) for r in moments(x, w)) > mp.mpf(10) ** -30:
        sys.exit("a moment does not hold")
    return [float(v) for v in x], [float(v) for v in w]


def text(x, w):
    rows = lambda v: "\n".join(f"    {repr(a)}," for a in v)  # noqa: E731
    return f"""//! Generated by scripts/gen_log_gauss.py; never edited by hand. The generalized Gauss rule on
//! [0, 1] exact for p^k and p^k log p, k = 0..{N - 1} (Ma, Rokhlin & Wandzura 1996).

pub const LOG_GAUSS_N: usize = {N};

pub const LOG_GAUSS_NODES: [f64; {N}] = [
{rows(x)}
];

pub const LOG_GAUSS_WEIGHTS: [f64; {N}] = [
{rows(w)}
];
"""


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="only check that the table is up to date")
    a = ap.parse_args()
    t = text(*rule())
    if a.check:
        if OUT.read_text(encoding="utf-8") != t:
            sys.exit(f"{OUT} is not up to date: run scripts/gen_log_gauss.py")
        print("up to date")
        return
    OUT.write_bytes(t.encode("utf-8"))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
