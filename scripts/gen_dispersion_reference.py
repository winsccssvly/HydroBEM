"""Reference roots of the finite-depth dispersion relation for test A3
(test-plan): with H = K h,

    x0 tanh x0 = H              (propagating mode, x0 = k0 h),
    xn tan xn = -H,  (n - 1/2) pi < xn < n pi   (evanescent modes).

Roots are bracketed analytically, found by mpmath's Anderson solver and
polished by Newton steps at 40 digits; each is checked to satisfy its equation
with a residual equivalent to a relative root error |f| / (|f'| x) <= 1e-35.

Writes tests/data/dispersion_reference.txt: H n x (n = 0 is the propagating root)

Usage: python scripts/gen_dispersion_reference.py
"""

from __future__ import annotations

import sys
from pathlib import Path

import mpmath as mp

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tests" / "data" / "dispersion_reference.txt"
DPS = 40


def x0(H):
    H = mp.mpf(H)
    lo = max(H, mp.sqrt(H)) * (1 - mp.mpf(10) ** -30)
    hi = (H + mp.sqrt(H * H + 4 * H)) / 2 * (1 + mp.mpf(10) ** -30)
    r = mp.findroot(lambda x: x * mp.tanh(x) - H, (lo, hi), solver="anderson")
    for _ in range(4):  # Newton polish
        t = mp.tanh(r)
        r -= (r * t - H) / (t + r * (1 - t * t))
    return r


def xn(H, n):
    H = mp.mpf(H)
    # d = n pi - x in (0, pi/2): (n pi - d) sin d - H cos d = 0
    npi = n * mp.pi
    g = lambda d: (npi - d) * mp.sin(d) - H * mp.cos(d)  # noqa: E731
    d = mp.findroot(g, (mp.mpf(0), mp.pi / 2), solver="anderson")
    for _ in range(4):  # Newton polish
        d -= g(d) / ((npi - d) * mp.cos(d) + (H - 1) * mp.sin(d))
    return npi - d


def main():
    mp.mp.dps = DPS
    Hs = [mp.mpf(10) ** (e / mp.mpf(4)) for e in range(-48, 33)]  # 1e-12 .. 1e8
    Hs += [mp.mpf(v) for v in ("0.5", "1", "2", "18.5", "19", "39.9", "40", "40.1")]
    Hs = [mp.mpf(float(H)) for H in Hs]  # exactly representable in double
    ns = list(range(1, 21)) + [50, 100, 1000]
    lines = [
        "# Generated by scripts/gen_dispersion_reference.py -- do not edit.",
        "# H n x  (n = 0: x tanh x = H; n >= 1: x tan x = -H)",
    ]
    worst = mp.mpf(0)
    for H in Hs:
        r = x0(H)
        t = mp.tanh(r)
        worst = max(worst, abs(r * t - H) / ((t + r * (1 - t * t)) * r))
        lines.append(f"{float(H)!r} 0 {mp.nstr(r, 25)}")
        for n in ns:
            r = xn(H, n)
            assert (n - 0.5) * mp.pi < r < n * mp.pi
            t = mp.tan(r)
            worst = max(worst, abs(r * t + H) / (abs(t + r * (1 + t * t)) * r))
            lines.append(f"{float(H)!r} {n} {mp.nstr(r, 25)}")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"{len(lines) - 2} roots written, largest relative root error {mp.nstr(worst, 3)}")
    if worst > mp.mpf(10) ** -35:
        sys.exit("residual check failed")


if __name__ == "__main__":
    main()
