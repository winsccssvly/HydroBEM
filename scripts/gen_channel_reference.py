"""Reference values for the channel kernel, in mpmath.

Writes tests/data/channel_reference.txt:
  W  re(z) im(z) re(w) im(w)          Faddeeva w(z) = exp(-z^2) erfc(-iz)
  F  k d x s re(F) im(F)              lattice sum F(x, s) = sum_j H0^(2)(k sqrt(x^2 + (s - j d)^2))

F is computed independently of the engine's Ewald and eigenfunction code:
for x > 0 by the eigenfunction (strip-mode) series
  F = (2i/d) sum_{n>=0} eps_n cos(alpha_n s) exp(-lb_n x) / lb_n,
  alpha_n = 2 pi n / d, lb_n = i sqrt(k^2 - alpha_n^2) or sqrt(alpha_n^2 - k^2),
summed to convergence in 40-digit arithmetic, and for x = 0 by the Kummer
form of Linton (1999, eq. 2.17): sum_n e^{i alpha_n s}/sqrt(alpha_n^2 + c^2)
= (d/pi) sum_n K0(c |s - n d|), with c = k: the terms k^2/alpha^3 and k^6/alpha^7 of
the difference summed in closed form (Clausen functions), the rest of order alpha^-11
summed directly over 3000 terms, and the K0 lattice sum by mpmath.nsum.

    python scripts/gen_channel_reference.py
"""

from pathlib import Path

import mpmath as mp

mp.mp.dps = 40
OUT = Path(__file__).resolve().parents[1] / "tests" / "data" / "channel_reference.txt"


def faddeeva(z):
    return mp.exp(-z * z) * mp.erfc(-1j * z)


def lb(n, k, d):
    al = 2 * mp.pi * n / d
    q = al * al - k * k
    return mp.sqrt(q) if q > 0 else 1j * mp.sqrt(-q)


def lattice_modal(x, s, k, d):
    total, n = mp.mpc(0), 0
    while True:
        b = lb(n, k, d)
        t = (1 if n == 0 else 2) * mp.cos(2 * mp.pi * n * s / d) * mp.exp(-b * x) / b
        total += t
        n += 1
        if mp.re(b) > 0 and mp.re(b) * x > 100:
            break
    return 2j / d * total


def lattice_x0(s, k, d):
    # psi (time factor e^{-iwt}) at x = 0: (1/2d) sum_n e^{i al s} (1/lam_n - 1/sqrt(al^2 + k^2))
    # + (1/2pi) sum_n K0(k |s - n d|), lam_n = sqrt(al^2 - k^2) or -i sqrt(k^2 - al^2); F = 4i conj(psi)
    def lam(n):
        al = 2 * mp.pi * n / d
        q = al * al - k * k
        return mp.sqrt(q) if q > 0 else -1j * mp.sqrt(-q)

    def term(n):
        al = 2 * mp.pi * n / d
        return (1 if n == 0 else 2) * mp.cos(al * s) * (1 / lam(n) - 1 / mp.sqrt(al * al + k * k))

    # Kummer: for alpha > k, 1/lam - 1/sqrt(al^2 + k^2) = k^2/al^3 + (5/8) k^6/al^7 + O(al^-11);
    # sum_{n>=1} 2 cos(n th) / al^p = 2 (d/2pi)^p clcos(p, th), th = 2 pi s / d
    nprop = int(k * d / (2 * mp.pi)) + 2
    th = 2 * mp.pi * s / d

    def kummer(n):
        al = 2 * mp.pi * n / d
        return 2 * mp.cos(al * s) * (k**2 / al**3 + mp.mpf(5) / 8 * k**6 / al**7)

    c = d / (2 * mp.pi)
    closed = 2 * k**2 * c**3 * mp.clcos(3, th) + mp.mpf(5) / 4 * k**6 * c**7 * mp.clcos(7, th)
    head = mp.fsum(term(n) for n in range(nprop)) + closed - mp.fsum(kummer(n) for n in range(1, nprop))
    rest = mp.fsum(term(n) - kummer(n) for n in range(nprop, nprop + 3000))
    first = (head + rest) / (2 * d)
    kz = mp.nsum(lambda n: mp.besselk(0, k * abs(s - n * d)), [-mp.inf, mp.inf])
    psi = first + kz / (2 * mp.pi)
    return 4j * mp.conj(psi)


def main():
    head = "# channel kernel reference values. Generated by scripts/gen_channel_reference.py (mpmath 40 digits)"
    lines = [head + " -- do not edit"]
    for z in (0.3 + 0.2j, 2.0 + 0.5j, -1.5 + 3.0j, 0.1 + 0.001j, 6.0 + 0.1j, 0.5 - 0.7j, -3.0 - 2.0j, 12.0 + 4.0j):
        w = faddeeva(mp.mpc(z))
        lines.append(f"W {mp.nstr(mp.re(z), 17)} {mp.nstr(mp.im(z), 17)} "
                     f"{mp.nstr(mp.re(w), 20)} {mp.nstr(mp.im(w), 20)}")
    d = mp.mpf(160)
    for k in (mp.mpf("0.05"), mp.mpf("0.2"), mp.mpf("0.6")):
        for x, s in ((0.5, 30.0), (4.0, -55.0), (25.0, 10.0), (60.0, 79.0), (250.0, -20.0), (0.0, 37.0),
                     (0.0, 140.0), (1.0, 0.7)):
            x, s = mp.mpf(x), mp.mpf(s)
            f = lattice_x0(s, k, d) if x == 0 else lattice_modal(x, s, k, d)
            lines.append(f"F {mp.nstr(k, 17)} {mp.nstr(d, 17)} {mp.nstr(x, 17)} {mp.nstr(s, 17)} "
                         f"{mp.nstr(mp.re(f), 20)} {mp.nstr(mp.im(f), 20)}")
            print(lines[-1], flush=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")


if __name__ == "__main__":
    main()
