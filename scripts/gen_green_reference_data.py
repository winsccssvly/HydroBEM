"""Reference data for test A2 (infinite depth, test-plan): Ft and dFt/dX at
points covering the whole (X, Y) quadrant, including the axes, the corner
near the origin, the table edges at 30 and the far regions.

Values come from Havelock's form (3b) at 30 digits; points with small R0 are
cross-checked against Newman's series (5), points with Y >= 1 against the
principal-value integral (3a). The run fails if (5) differs by more than
1e-20 or (3a) by more than 1e-9 (the oscillatory infinite tail of (3a) limits
mpmath's quadrature to about 1e-11).

Writes tests/data/green_inf_reference.txt: X Y Ft dFt/dX

Usage: python scripts/gen_green_reference_data.py [--workers N]
"""

from __future__ import annotations

import argparse
import multiprocessing as mpc
import sys
from pathlib import Path

import mpmath as mp
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import green_reference as gr  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "tests" / "data" / "green_inf_reference.txt"


def _points():
    rng = np.random.default_rng(42)
    pts = []
    edges = [0.0, 1e-8, 1e-4, 0.01, 0.5, 1.0, 2.0, 5.0, 10.0, 29.999, 30.0, 30.001, 45.0, 80.0, 200.0]
    for x in edges:
        for y in edges:
            if x == 0 and y == 0:
                continue
            pts.append((x, y))
    for _ in range(600):  # inside the tables
        pts.append(tuple(rng.uniform(0, 30, 2)))
    for _ in range(150):  # near the origin, log-uniform
        r = 10 ** rng.uniform(-6, 0)
        t = rng.uniform(0, np.pi / 2)
        pts.append((r * np.cos(t), r * np.sin(t)))
    for _ in range(250):  # far regions
        pts.append((10 ** rng.uniform(np.log10(25), 3), rng.uniform(0, 40)))
        pts.append((rng.uniform(0, 40), 10 ** rng.uniform(np.log10(25), 2.5)))
    return pts


def _eval(p):
    mp.mp.dps = gr.DPS
    X, Y = mp.mpf(p[0]), mp.mpf(p[1])
    F, FX = gr.Ft_3b(X, Y)
    c5 = c3a = 0.0
    R0 = mp.sqrt(X * X + Y * Y)
    if R0 < 2:
        c5 = float(abs(gr.Ft_series5(X, Y) - F))
    if Y >= 1 and X < 20 and p[0] % 1 < 0.2:  # subset: (3a) is slow
        c3a = float(abs(gr.Ft_3a(X, Y) - F))
    return p[0], p[1], mp.nstr(F, 20), mp.nstr(FX, 20), c5, c3a


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=max(1, mpc.cpu_count() - 2))
    args = ap.parse_args()
    with mpc.Pool(args.workers) as pool:
        res = pool.map(_eval, _points(), chunksize=8)
    w5, w3a = max(r[4] for r in res), max(r[5] for r in res)
    lines = ["# Generated by scripts/gen_green_reference_data.py -- do not edit.", "# X Y Ft dFt/dX"]
    lines += [f"{r[0]:.17g} {r[1]:.17g} {r[2]} {r[3]}" for r in res]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"{len(res)} points written; largest difference to (5) {w5:.2e}, to (3a) {w3a:.2e}")
    if w5 > 1e-20 or w3a > 1e-9:
        sys.exit("cross-check failed")


if __name__ == "__main__":
    main()
