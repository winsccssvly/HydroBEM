"""The output stage of the Green function table generators: writes a Rust module
(crates/hydrobem/src/tables/*.rs) of integer and real constants, the checksum and the coefficient
arrays.

Used by gen_green_tables.py and gen_green_finite_tables.py. No third-party imports.

Each double is written as Python's repr, the shortest decimal that rounds to the same double;
Rust parses float literals with correct rounding, so every coefficient round-trips bit for bit
(the engine verifies the FNV-1a 64 checksum at run time). The arrays are `static` (one copy in
the binary, not inlined at every use as a `const` would be).
"""

from __future__ import annotations

import math
import struct
from pathlib import Path


def fnv1a64(values):
    """FNV-1a 64 of the little-endian bytes of the doubles (crate::constants::fnv1a)."""
    h = 0xCBF29CE484222325
    for v in values:
        for byte in struct.pack("<d", float(v)):
            h ^= byte
            h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def rust_f64(v) -> str:
    """A Rust f64 literal that parses to exactly the double v."""
    v = float(v)
    if not math.isfinite(v):
        raise ValueError(f"non-finite table value {v!r}")
    s = repr(v)  # shortest round-trip form: '1.5', '-0.0', '1e-05', '1.2345e+20'
    if "e" in s and "." not in s.split("e")[0]:
        m, e = s.split("e")
        s = f"{m}.0e{e}"
    return s.replace("e+", "e")


def rust_array(name, values, per_line=4, comment=None):
    vals = [float(v) for v in values]
    lines = [] if comment is None else [f"/// {comment}"]
    lines.append(f"pub static {name}: [f64; {len(vals)}] = [")
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(rust_f64(v) for v in vals[i : i + per_line]) + ",")
    lines.append("];")
    return "\n".join(lines)


def write_rust_tables(path, generator, summary, ints, reals, checksum, arrays):
    """Writes the Rust table module.

    ints, reals: [(NAME, value)] constants (i32, f64); arrays: [(NAME, values, per_line, comment)].
    The checksum (FNV-1a 64 of all arrays in order) is checked here before writing.
    """
    allv = [float(v) for _, values, *_ in arrays for v in values]
    if fnv1a64(allv) != checksum:
        raise SystemExit(f"{path}: the checksum does not match the coefficients")
    body = [
        f"//! Generated by {generator} -- do not edit.",
        f"//! {summary}",
        "#![allow(clippy::approx_constant)] // tabulated coefficients, some of them near a constant like 2/pi",
        "",
    ]
    body += [f"pub const {n}: i32 = {int(v)};" for n, v in ints]
    body += [f"pub const {n}: f64 = {rust_f64(v)};" for n, v in reals]
    body.append(f"pub const CHECKSUM: u64 = 0x{checksum:016X};")
    for name, values, per_line, comment in arrays:
        body.append(rust_array(name, values, per_line, comment))
    body.append("")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(body), encoding="utf-8", newline="\n")
