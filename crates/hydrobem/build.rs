//! Writes the build information of `build_info()`: the version, the commit, the build type
//! and the compiler. Nothing is linked: the engine is pure Rust.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

// the commit (git describe of the repository), the build type and the compiler
fn build_info(out_dir: &Path) {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let repo = manifest.join("..").join("..");
    let commit = Command::new("git")
        .args(["describe", "--always", "--dirty", "--abbrev=12"])
        .current_dir(&repo)
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .filter(|s| !s.is_empty())
        .unwrap_or_else(|| "unknown".to_string());
    let build_type = if env::var("PROFILE").as_deref() == Ok("release") { "Release" } else { "Debug" };
    let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".to_string());
    let compiler = Command::new(rustc)
        .arg("--version")
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_else(|| "rustc".to_string());
    let text = format!(
        "// Generated by build.rs -- do not edit.\n\
         pub const VERSION: &str = {:?};\npub const COMMIT: &str = {:?};\n\
         pub const BUILD_TYPE: &str = {:?};\npub const COMPILER: &str = {:?};\n",
        env::var("CARGO_PKG_VERSION").unwrap(),
        commit,
        build_type,
        compiler
    );
    let path = out_dir.join("build_info_gen.rs");
    if fs::read_to_string(&path).ok().as_deref() != Some(text.as_str()) {
        fs::write(&path, text).unwrap();
    }
    // a new commit or a change of the working tree rewrites the commit
    for p in [".git/HEAD", ".git/index"] {
        if repo.join(p).exists() {
            println!("cargo:rerun-if-changed={}", repo.join(p).display());
        }
    }
}

fn main() {
    build_info(&PathBuf::from(env::var("OUT_DIR").unwrap()));
    println!("cargo:rerun-if-changed=build.rs");
}
